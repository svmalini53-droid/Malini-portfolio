// src/ai/flows/enhance-bio-with-ai.ts
'use server';

/**
 * @fileOverview This file contains a Genkit flow to enhance a user's biography using AI.
 *
 * It defines:
 * - enhanceBioWithAI: The main function to trigger the bio enhancement flow.
 * - EnhanceBioWithAIInput: The input type for the enhanceBioWithAI function.
 * - EnhanceBioWithAIOutput: The output type for the enhanceBioWithAI function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

// Define the input schema
const EnhanceBioWithAIInputSchema = z.object({
  bio: z.string().describe('The original biography text to enhance.'),
});
export type EnhanceBioWithAIInput = z.infer<typeof EnhanceBioWithAIInputSchema>;

// Define the output schema
const EnhanceBioWithAIOutputSchema = z.object({
  enhancedBio: z.string().describe('The enhanced biography text generated by the AI.'),
});
export type EnhanceBioWithAIOutput = z.infer<typeof EnhanceBioWithAIOutputSchema>;

// Exported function to call the flow
export async function enhanceBioWithAI(input: EnhanceBioWithAIInput): Promise<EnhanceBioWithAIOutput> {
  return enhanceBioWithAIFlow(input);
}

// Define the prompt
const enhanceBioPrompt = ai.definePrompt({
  name: 'enhanceBioPrompt',
  input: {schema: EnhanceBioWithAIInputSchema},
  output: {schema: EnhanceBioWithAIOutputSchema},
  prompt: `You are a professional resume writer. Please improve the following biography text to be more engaging and impactful, while maintaining a professional tone:

Original Bio: {{{bio}}}

Enhanced Bio:`, // Handlebars syntax
});

// Define the flow
const enhanceBioWithAIFlow = ai.defineFlow(
  {
    name: 'enhanceBioWithAIFlow',
    inputSchema: EnhanceBioWithAIInputSchema,
    outputSchema: EnhanceBioWithAIOutputSchema,
  },
  async input => {
    const {output} = await enhanceBioPrompt(input);
    return output!;
  }
);
